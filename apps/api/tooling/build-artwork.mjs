// Reuse the progression source cache; image indexes must come from the same pinned commit.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const cache = process.argv[2];
if (!cache) throw new Error('Supply the pinned genshin-db source-cache directory.');
const { commit, collected } = JSON.parse(readFileSync(resolve(cache, 'source-data.json'), 'utf8'));
if (commit !== '49a6544a6c6ae36089cb42fa591fc46f01de8bcf')
  throw new Error('Unexpected source commit.');
const keyOf = (name) =>
  name
    .normalize('NFKD')
    .replace(/[\u0300-\u036f'’"“”]/g, '')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
const mapping = { characters: {}, weapons: {} };
const metadata = { characters: {}, weapons: {} };
const hashes = {};
for (const kind of ['characters', 'weapons']) {
  const text = readFileSync(resolve(cache, `images-${kind}.json`), 'utf8');
  hashes[kind] = createHash('sha256').update(text).digest('hex');
  const images = JSON.parse(text);
  const prefix = kind === 'characters' ? 'UI_AvatarIcon_' : 'UI_EquipIcon_';
  for (const { file, data } of collected[kind]) {
    const key = keyOf(data.name);
    const icon = images[file.replace('.json', '')]?.filename_icon;
    if (!icon?.startsWith(prefix)) throw new Error(`Missing verified icon: ${kind}/${file}`);
    mapping[kind][key] = icon.slice(prefix.length);
    metadata[kind][key] = {
      name: data.name,
      rarity: data.rarity,
      ...(kind === 'characters' ? { element: data.elementText, weapon: data.weaponText } : {}),
    };
  }
}
const alias = (kind, key, source, override = {}) => {
  mapping[kind][key] = mapping[kind][source];
  metadata[kind][key] = { ...metadata[kind][source], ...override };
};
alias('characters', 'Traveler', 'Aether', { name: 'Traveler' });
for (const element of ['Anemo', 'Geo', 'Electro', 'Dendro', 'Hydro', 'Pyro', 'Cryo']) {
  alias('characters', `Traveler${element}`, 'Aether', { name: `Traveler (${element})`, element });
  for (const traveler of ['Aether', 'Lumine']) {
    alias('characters', `${traveler}${element}`, traveler, {
      name: `${traveler} (${element})`,
      element,
    });
  }
}
alias('characters', 'Kukishinobu', 'KukiShinobu');
alias('weapons', 'Widsith', 'TheWidsith');
const root = resolve(import.meta.dirname, '../../../');
writeFileSync(
  resolve(root, 'apps/web/src/lib/asset-mapping.ts'),
  `// Generated by apps/api/tooling/build-artwork.mjs from genshin-db ${commit}.\n` +
    `// Source and license: docs/plans/section4-ui/sources.md.\n` +
    `export const ASSET_MAPPING: { characters: Record<string, string>; weapons: Record<string, string> } = ${JSON.stringify(mapping, null, 2)};\n`,
);
writeFileSync(
  resolve(root, 'apps/web/src/lib/artwork-metadata.json'),
  JSON.stringify(metadata, null, 2) + '\n',
);
console.log(
  JSON.stringify({
    commit,
    imageIndexHashes: hashes,
    characters: Object.keys(mapping.characters).length,
    weapons: Object.keys(mapping.weapons).length,
  }),
);
